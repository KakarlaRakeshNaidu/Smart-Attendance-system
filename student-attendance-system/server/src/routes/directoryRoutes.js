const express = require('express');
const { protect, requireRole } = require('../middleware/authMiddleware');
const { studentUploader } = require('../middleware/uploadMiddleware');
const C = require('../controllers/directoryController'),
    S = require('../controllers/academicDirectoryController'),
    I = require('../controllers/institutionAttendanceController');
const router = express.Router();
router.use(protect, requireRole('admin'), require('../middleware/validateRequest'));
router.get('/stats', C.stats);
router.get('/audit-logs', C.auditLogs);
router.get('/teachers/:id/access', C.getAccess);
router.post('/teachers/:id/access', C.grantAccess);
router.delete('/teachers/:id/access/:accessId', C.revokeAccess);
router.get('/:kind(teachers|students)', C.list);
router.post('/:kind(teachers|students)', studentUploader.single('profilePhoto'), C.create);
router.put('/:kind(teachers|students)/:id/archive', C.archive);
router.put('/:kind(teachers|students)/:id/reset-password', C.resetPassword);
router.put('/:kind(teachers|students)/:id', C.update);
router.delete('/:kind(teachers|students)/:id', C.remove);
router.get('/classes', S.classes);
router.post('/classes', S.createClass);
router.put('/classes/:id', S.updateClass);
router.delete('/classes/:id', S.updateClass);
router.get('/subjects', S.subjects);
router.post('/subjects', S.createSubject);
router.put('/subjects/:id', S.updateSubject);
router.get('/:kind(enrollments|assignments)', S.entries);
router.post('/:kind(enrollments|assignments)', S.addEntry);
router.delete('/:kind(enrollments|assignments)/:id', S.removeEntry);
router.get('/attendance-sessions', I.list);
router.put('/attendance/:id/correct', I.correct);
module.exports = router;
