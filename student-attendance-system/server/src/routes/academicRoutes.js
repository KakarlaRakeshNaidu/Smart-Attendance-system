const router = require('express').Router();
const { protect, requireRole, requireTeacherProfile } = require('../middleware/authMiddleware');
const C = require('../controllers/academicController');
router.use(protect);
router.use((req,res,next) => req.userRole === 'teacher' ? requireTeacherProfile(req,res,next) : next());
const admin = requireRole('admin'), staff = requireRole('admin','teacher'), teacher = requireRole('teacher');
router.get('/structures/:kind',admin,C.structures);
router.post('/structures/:kind',admin,C.structures);
router.patch('/structures/:kind/:id',admin,C.structures);
router.get('/profiles',admin,C.profiles);
router.get('/offerings',C.offerings);
router.post('/offerings',admin,C.offerings);
router.get('/offerings/:id',C.offeringDetail);
router.patch('/offerings/:id',admin,C.archiveOffering);
router.post('/offerings/:id/:kind',admin,C.link);
router.patch('/offerings/:id/:kind/:linkId',admin,C.link);
router.get('/sessions',C.sessions);
router.post('/sessions',staff,C.createSession);
router.get('/sessions/:id',C.getSession);
router.patch('/sessions/:id',staff,C.manageSession);
router.post('/sessions/:id/attendance',teacher,C.manual);
router.post('/sessions/:id/recognise',teacher,C.recognise);
router.post('/sessions/:id/finalise',teacher,C.finalise);
router.delete('/sessions/:id/attendance',teacher,C.reset);
router.get('/sessions/:id/export',staff,C.exportSession);
router.get('/my-summary',requireRole('student'),C.mySummary);
router.get('/legacy',C.legacyList);
router.post('/legacy/:id/:action',admin,(req,res,next) => ['preview','convert'].includes(req.params.action) ? next() : res.status(404).json({success:false,message:'Mapping action not found.'}),C.mapLegacy);
module.exports = router;
